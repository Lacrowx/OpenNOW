#!/usr/bin/env python3
"""Writes ios/OpenNOWtvOS/Sources/TVAudioSelfTestClips.swift: two short Opus multistream clips
(5.1 and 7.1, 5 ms packets like the seat's, one sine per speaker) for the audio self-test.

Needs ffmpeg built with libopus. Run from the repository root.
"""
import base64
import pathlib
import struct
import subprocess
import tempfile

TONES = {"FL": 300, "FR": 500, "FC": 700, "LFE": 80, "BL": 1100, "BR": 1300, "SL": 1700, "SR": 1900}
# Name, ffmpeg layout, speakers, and the OpusHead values libopus must have used:
# channels, streams, coupled streams, mapping table. TVAudioSelfTest.swift relies on them.
CLIPS = [
    ("surround51", "5.1", ["FL", "FR", "FC", "LFE", "BL", "BR"], (6, 4, 2, [0, 4, 1, 2, 3, 5])),
    ("surround71", "7.1", ["FL", "FR", "FC", "LFE", "BL", "BR", "SL", "SR"], (8, 5, 3, [0, 6, 1, 2, 3, 4, 5, 7])),
]
OUTPUT = pathlib.Path("ios/OpenNOWtvOS/Sources/TVAudioSelfTestClips.swift")


def encode(layout, speakers, expected_head, folder):
    command = ["ffmpeg", "-hide_banner", "-loglevel", "error", "-y"]
    for speaker in speakers:
        command += ["-f", "lavfi", "-i", f"sine=f={TONES[speaker]}:r=48000:d=0.3"]
    inputs = "".join(f"[{index}]" for index in range(len(speakers)))
    mapping = "|".join(f"{index}.0-{speaker}" for index, speaker in enumerate(speakers))
    clip = folder / f"{layout}.opus"
    command += ["-filter_complex",
                f"{inputs}join=inputs={len(speakers)}:channel_layout={layout}:map={mapping}[a]",
                "-map", "[a]", "-c:a", "libopus", "-frame_duration", "5", "-b:a", "448k",
                "-mapping_family", "1", str(clip)]
    subprocess.run(command, check=True)

    data = clip.read_bytes()
    packets = []
    current = b""
    position = 0
    while position < len(data):
        if data[position:position + 4] != b"OggS":
            raise SystemExit(f"{layout}: not an Ogg page at byte {position}")
        count = data[position + 26]
        cursor = position + 27 + count
        for size in data[position + 27:position + 27 + count]:
            current += data[cursor:cursor + size]
            cursor += size
            if size < 255:
                packets.append(current)
                current = b""
        position = cursor

    head = packets[0]
    found = (head[9], head[19], head[20], list(head[21:21 + head[9]]))
    if found != expected_head:
        raise SystemExit(f"{layout}: the encoder used {found}; the self-test expects {expected_head}")
    # The first two packets are OpusHead and OpusTags; the rest is audio.
    return b"".join(struct.pack("<H", len(packet)) + packet for packet in packets[2:])


def main():
    lines = [
        "// Generated by BuildScripts/make-surround-clips.py. Do not edit.",
        "#if DEBUG",
        "/// Opus multistream clips for `TVAudioSelfTest`: 0.3 s in 5 ms packets, one sine per speaker",
        "/// (FL 300 Hz, FR 500, FC 700, LFE 80, BL 1100, BR 1300, SL 1700, SR 1900). Each is the",
        "/// base64 of its packets, every packet preceded by its length as a little-endian UInt16.",
        "enum TVAudioSelfTestClips {",
    ]
    with tempfile.TemporaryDirectory() as folder:
        for name, layout, speakers, expected_head in CLIPS:
            clip = encode(layout, speakers, expected_head, pathlib.Path(folder))
            lines.append(f'    static let {name} = "{base64.b64encode(clip).decode()}"')
    lines += ["}", "#endif", ""]
    OUTPUT.write_text("\n".join(lines))
    print(f"wrote {OUTPUT}")


if __name__ == "__main__":
    main()
